  // t(key, vars) resolves a UI chrome string for the active language, substituting any
  // {{name}} placeholders with vars.name. Falls back to English, then to the raw key, so a
  // missing translation never renders blank.
  window.t = function(key, vars){
    const lang = currentLang();
    const dict = window.UI_STRINGS[lang] || {};
    let str = dict[key];
    if(str === undefined || str === "") str = window.UI_STRINGS.en[key];
    if(str === undefined || str === "") str = key;
    if(vars){
      Object.keys(vars).forEach(function(name){
        str = str.split("{{" + name + "}}").join(String(vars[name]));
      });
    }
    return str;
  };
